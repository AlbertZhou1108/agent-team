export function normalizeModelPolicy({ mode = 'user', rules } = {}) {
  if (!['smart', 'user'].includes(mode)) throw new Error('模型策略mode必须为smart或user');
  const value = typeof rules === 'string' ? rules.trim() : '';
  if (!value) {
    if (mode === 'smart') return { mode, rules: SMART_COST_RULES };
    return { mode, rules: DEFAULT_USER_MODEL_RULES };
  }
  if (value.length > 48000) throw new Error('模型策略rules过长');
  return { mode, rules: value };
}

// 成员模型选择的展示摘要,互动卡与日志使用同一文案。
export function memberModelSummary(selection) {
  return selection
    ? `${selection.model_provider ? `${selection.model_provider}/` : ''}${selection.model}（强度 ${selection.reasoning_effort}）`
    : '宿主默认模型';
}
